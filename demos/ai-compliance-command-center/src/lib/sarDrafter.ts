// SAR Drafting AI — GPT-4o + Prompt Library. Produces a draft Suspicious
// Activity Report narrative grounded in the case facts. In production this calls
// Azure OpenAI with the `sar-narrative-v2` template; here we deterministically
// assemble an equivalent narrative from the case evidence.

import type { Case, SarDraft } from './types'
import { id } from './random'
import { getPrompt } from './promptLibrary'

export function draftSar(c: Case, now: number, regulator: 'FinCEN' | 'FCA' = 'FinCEN'): SarDraft {
  const t = c.alert.transaction
  const a = c.alert.assessment
  const template = getPrompt('sar-narrative-v2')

  const indicators = a.reasons.length
    ? a.reasons.map((r) => `  • ${r}`).join('\n')
    : '  • Pattern-based behavioural anomaly'

  const screening = a.screeningHits.length
    ? a.screeningHits
        .map((h) => `${h.list} match on "${h.matchedName}" (${h.score}% confidence)`)
        .join('; ')
    : 'no direct watchlist matches'

  const narrative = `[Generated by SAR Drafting AI using prompt "${template?.id ?? 'sar-narrative-v2'}"]

SUBJECT(S): ${t.originator} (originator) and ${t.beneficiary} (beneficiary).

ACTIVITY: On ${new Date(t.timestamp).toUTCString()}, a ${t.type.toUpperCase()} transaction of ${t.currency} ${t.amount.toLocaleString()} was processed via the ${t.channel} channel from ${t.originatorCountry} to ${t.beneficiaryCountry}.

BASIS FOR SUSPICION: The AI Risk Score Engine assigned a fused risk score of ${a.score}/100 (model ${a.modelScore}, GPT-4o ${a.llmScore}). Screening returned ${screening}. Contributing indicators:
${indicators}

ASSESSMENT: ${a.narrative}

The above activity is being reported as potentially suspicious pending ${regulator} review. This draft was generated by AI and requires human approval before filing.`

  return {
    id: id('sar'),
    draftedAt: new Date(now).toISOString(),
    narrative,
    regulator,
    approved: false,
  }
}
