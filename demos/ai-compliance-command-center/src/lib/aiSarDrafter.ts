// AI SAR Drafter — calls Claude (claude-sonnet-4-6) when VITE_ANTHROPIC_API_KEY is set,
// otherwise falls back to the deterministic stub in sarDrafter.ts.
// Uses dangerouslyAllowBrowser because this is a client-side demo app.

import Anthropic from '@anthropic-ai/sdk'
import type { Case, SarDraft } from './types'
import { draftSar } from './sarDrafter'
import { getPrompt } from './promptLibrary'
import { withRetry } from './retry'
import { id } from './random'

export async function draftSarAI(
  c: Case,
  now: number,
  regulator: 'FinCEN' | 'FCA' = 'FinCEN',
): Promise<SarDraft> {
  const apiKey = import.meta.env.VITE_ANTHROPIC_API_KEY

  if (!apiKey) {
    return draftSar(c, now, regulator)
  }

  const t = c.alert.transaction
  const a = c.alert.assessment
  const template = getPrompt('sar-narrative-v2')

  const systemPrompt =
    template?.template.replace('{regulator}', regulator) ??
    `You are an AML investigator drafting a Suspicious Activity Report narrative for ${regulator} filing.`

  const screeningText =
    a.screeningHits.length > 0
      ? a.screeningHits.map((h) => `${h.list} match on "${h.matchedName}" (${h.score}%)`).join('; ')
      : 'No watchlist matches'

  const caseContext = `CASE ID: ${c.id}
TRANSACTION: ${t.type.toUpperCase()} of ${t.currency} ${t.amount.toLocaleString()} on ${new Date(t.timestamp).toUTCString()}
ORIGINATOR: ${t.originator} (${t.originatorCountry}) via ${t.channel}
BENEFICIARY: ${t.beneficiary} (${t.beneficiaryCountry})
RISK SCORE: ${a.score}/100 (band: ${a.band}) | MODEL: ${a.modelScore} | LLM: ${a.llmScore}
SCREENING: ${screeningText}
RISK INDICATORS:
${a.reasons.map((r) => `  • ${r}`).join('\n')}
RISK NARRATIVE: ${a.narrative}
INVESTIGATION NOTES: ${c.notes.length > 0 ? c.notes.join(' | ') : 'None'}
CASE OPENED: ${c.openedAt} by ${c.openedBy}`

  const client = new Anthropic({ apiKey, dangerouslyAllowBrowser: true })

  let message
  try {
    message = await withRetry(
      () => client.messages.create({
        model: 'claude-sonnet-4-6',
        max_tokens: 1024,
        system: systemPrompt,
        messages: [{ role: 'user', content: `Draft a SAR narrative for the following case:\n\n${caseContext}` }],
      }),
      { maxAttempts: 2, baseDelayMs: 800 },
    )
  } catch {
    // API unavailable after retries — fall back to the deterministic stub
    // so the analyst always receives a draft rather than a silent failure.
    return draftSar(c, now, regulator)
  }

  const aiText = message.content[0].type === 'text' ? message.content[0].text : ''
  const narrative = `[Generated by Claude SAR Drafting AI · prompt "${template?.id ?? 'sar-narrative-v2'}" · model ${message.model}]

${aiText}`

  return {
    id: id('sar'),
    draftedAt: new Date(now).toISOString(),
    narrative,
    regulator,
    approved: false,
  }
}
