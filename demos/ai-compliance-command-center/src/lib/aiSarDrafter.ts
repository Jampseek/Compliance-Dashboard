// AI SAR Drafter — routes through the AI Gateway (Azure Foundry → Anthropic → stub).
// The gateway's decision tree maps sar_drafting to the complex-reasoning tier and
// enforces role policy + monthly budget caps before any tokens are spent.

import type { Case, SarDraft } from './types'
import type { Role } from './rbac'
import { draftSar } from './sarDrafter'
import { getPrompt } from './promptLibrary'
import { invokeModel } from './aiGateway'
import { PRINCIPALS } from './rbac'
import { id } from './random'

export async function draftSarAI(
  c: Case,
  now: number,
  regulator: 'FinCEN' | 'FCA' = 'FinCEN',
  role: Role = 'investigator',
): Promise<SarDraft> {
  const t = c.alert.transaction
  const a = c.alert.assessment
  const template = getPrompt('sar-narrative-v2')

  const systemPrompt =
    template?.template.replace('{regulator}', regulator) ??
    `You are an AML investigator drafting a Suspicious Activity Report narrative for ${regulator} filing.`

  const screeningText =
    a.screeningHits.length > 0
      ? a.screeningHits.map((h) => `${h.list} match on "${h.matchedName}" (${h.score}%)`).join('; ')
      : 'No watchlist matches'

  const caseContext = `CASE ID: ${c.id}
TRANSACTION: ${t.type.toUpperCase()} of ${t.currency} ${t.amount.toLocaleString()} on ${new Date(t.timestamp).toUTCString()}
ORIGINATOR: ${t.originator} (${t.originatorCountry}) via ${t.channel}
BENEFICIARY: ${t.beneficiary} (${t.beneficiaryCountry})
RISK SCORE: ${a.score}/100 (band: ${a.band}) | MODEL: ${a.modelScore} | LLM: ${a.llmScore}
SCREENING: ${screeningText}
RISK INDICATORS:
${a.reasons.map((r) => `  • ${r}`).join('\n')}
RISK NARRATIVE: ${a.narrative}
INVESTIGATION NOTES: ${c.notes.length > 0 ? c.notes.join(' | ') : 'None'}
CASE OPENED: ${c.openedAt} by ${c.openedBy}`

  const res = await invokeModel({
    taskCategory: 'sar_drafting',
    role,
    actor: PRINCIPALS[role].name,
    system: systemPrompt,
    prompt: `Draft a SAR narrative for the following case:\n\n${caseContext}`,
    maxTokens: 1024,
  })

  if (!res.ok) {
    // Fall back to the deterministic stub so the analyst always receives a draft.
    const stub = draftSar(c, now, regulator)
    if (res.reason === 'budget_cap') {
      stub.narrative = `[AI CALL BLOCKED — monthly AI budget cap reached for this role. Deterministic fallback used. Request a cap increase or budget reallocation on the AI Governance page.]\n\n${stub.narrative}`
    } else if (res.reason === 'policy') {
      stub.narrative = `[AI CALL BLOCKED — the complex-reasoning model tier is not permitted for this role under AI usage policy. Deterministic fallback used. See the AI Governance page.]\n\n${stub.narrative}`
    }
    return stub
  }

  const narrative = `[Generated by Claude SAR Drafting AI · prompt "${template?.id ?? 'sar-narrative-v2'}" · model ${res.model} · via ${res.provider}]

${res.text}`

  return {
    id: id('sar'),
    draftedAt: new Date(now).toISOString(),
    narrative,
    regulator,
    approved: false,
  }
}
